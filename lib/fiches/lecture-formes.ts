/**
 * La poésie, la bande dessinée, le théâtre, la lecture libre.
 *
 * Quatre rituels, trente minutes. Deux s'appuient sur ce que l'enfant a en main, et la fiche dit alors comment mener plutôt que quoi lire. Les deux autres portent leur texte, écrit pour ce cahier.
 *
 * Ce qu'une fiche donne, et pourquoi : voir `lib/fiches/types.ts`. En deux
 * mots — le matériel exact, le corrigé quand il y en a un, et ce qu'on
 * regarde. Un adulte qui l'ouvre ne doit plus rien avoir à chercher.
 *
 * **Réservé aux adultes** : ces fiches portent les corrigés.
 *
 * ## Pourquoi aucune fiche d'ici n'a de champ `corrige`
 *
 * Lire un poème à voix haute, jouer une scène, raconter une planche : il n'y a
 * pas de bonne réponse à cocher. Mais il y a des réponses attendues, et elles
 * ne manquent pas pour autant — elles sont écrites **dans le matériel**, à la
 * suite de la question, après une flèche. « Quels deux mots riment au premier
 * vers ? → grenier / panier. » L'adulte a donc tout sous les yeux dans un seul
 * bloc, au lieu de faire l'aller-retour entre deux colonnes, et la fiche reste
 * une fiche d'adulte : elle porte les réponses.
 *
 * ## Ce que les textes sont
 *
 * Les poèmes et les scènes de théâtre ont été **écrits pour ce cahier**, sauf
 * quatre poèmes du domaine public, cités avec leur auteur : La Fontaine (mort
 * en 1695), Verlaine (1896), Marceline Desbordes-Valmore (1859). Rien ici
 * n'est recopié d'une œuvre encore protégée, et c'est une contrainte, pas une
 * préférence : le dépôt est privé mais le site est public.
 *
 * Rien de tout ceci n'a été relu par un enseignant. Ça doit l'être.
 */

