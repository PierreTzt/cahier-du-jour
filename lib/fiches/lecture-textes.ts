/**
 * La lecture de textes, à voix haute et silencieuse.
 *
 * Quatre rituels, trente minutes. Une fiche donne **le texte lui-même**, écrit
 * pour ce cahier — on ne recopie aucune œuvre sous droits — avec ses questions
 * et leurs réponses.
 *
 * Ce qu'une fiche donne, et pourquoi : voir `lib/fiches/types.ts`. En deux
 * mots — le matériel exact, le corrigé quand il y en a un, et ce qu'on
 * regarde. Un adulte qui l'ouvre ne doit plus rien avoir à chercher.
 *
 * **Réservé aux adultes** : ces fiches portent les corrigés.
 *
 * ## Comment lire le matériel d'une fiche
 *
 * Chaque entrée du matériel est un paragraphe. Selon le rituel :
 *
 *   - **Lecture à voix haute** — le matériel est le texte, une ligne par
 *     ligne, avec les respirations marquées. Une barre oblique `/` veut dire
 *     qu'on reprend son souffle ; deux barres `//` qu'on s'arrête, comme à un
 *     point. Il n'y a pas de corrigé : on écoute, on ne corrige pas.
 *   - **Lecture silencieuse** — le texte tient en quatre paragraphes, et le
 *     corrigé donne, dans le même ordre, les quatre choses qu'un récit juste
 *     contient. Ce sont des repères pour écouter, pas une grille à cocher.
 *   - **Lecture et questions**, **Lecture d'un documentaire** — le texte
 *     d'abord, paragraphe par paragraphe, puis les cinq questions. Le corrigé
 *     suit le matériel entrée pour entrée : en face d'un paragraphe de texte
 *     il n'y a rien à corriger, et on lit « — ».
 *
 * ## Les textes
 *
 * Ils sont écrits pour ce cahier, et ils sont de moi. Aucun n'est extrait d'un
 * livre : un texte sous droits n'a pas sa place dans un dépôt privé recopié
 * sur un écran, et un texte du domaine public de 1880 ne se lit pas comme une
 * page d'aujourd'hui. Ils vont du récit court au texte documentaire, du
 * dialogue au discours, et ils suivent l'année : les premiers tiennent en
 * phrases brèves, les derniers demandent du souffle et de l'attention.
 *
 * Rien de tout ceci n'a été relu par un enseignant. Ça doit l'être.
 */

