/**
 * La production d’écrit. Huit rituels, cinquante-quatre séances de vingt-cinq minutes.
 *
 * Une fiche donne **le sujet exact**, l’amorce s’il en faut une, et ce qu’on regarde ensemble dans ce qu’il a écrit — trois ou quatre choses précises, jamais une note.
 *
 * Ce qu’une fiche donne, et pourquoi : voir `lib/fiches/types.ts`. En deux
 * mots — le matériel exact, le corrigé quand il y en a un, et ce qu’on
 * regarde. Un adulte qui l’ouvre ne doit plus rien avoir à chercher.
 *
 * **Ici, pas de corrigé** : un texte n’a pas de bonne réponse. Ce qui en tient
 * lieu est dans `regarder` — la commande que le texte devait remplir, dans
 * l’ordre où on la relit avec lui. On lit à voix haute, on nomme ce qui est
 * là, on répare ensemble ce qui manque. On ne compte rien.
 *
 * Les codes vont de `rd-suite-01` à `rd-probleme-04` : le préfixe dit le
 * rituel, le numéro dit le rang dans l’année. Une série va du plus simple au
 * plus exigeant, de septembre à juillet.
 *
 * **Réservé aux adultes** : ces fiches portent les corrigés.
 *
 * Rien de tout ceci n’a été relu par un enseignant. Ça doit l’être.
 */

